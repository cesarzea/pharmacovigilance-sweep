-- V004: grants. Run-time roles never get UPDATE or DELETE on SWEEP, REVIEW or AUDIT.
USE ROLE PVSWEEP_ADMIN;
USE DATABASE PVSWEEP;

GRANT USAGE ON DATABASE PVSWEEP TO ROLE PVSWEEP_PIPELINE, ROLE PVSWEEP_AGENT, ROLE PVSWEEP_REVIEW_APP,
  ROLE PVSWEEP_REVIEWER, ROLE PVSWEEP_ANALYST, ROLE PVSWEEP_CI;

-- Pipeline: read sources, write results.
GRANT USAGE ON SCHEMA REF, SRC, PV, AGENT_API, SWEEP, AUDIT, EVAL, OPS TO ROLE PVSWEEP_PIPELINE;
GRANT SELECT ON ALL TABLES IN SCHEMA REF, SRC, PV, EVAL TO ROLE PVSWEEP_PIPELINE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA REF, SRC, PV, EVAL TO ROLE PVSWEEP_PIPELINE;
GRANT SELECT ON ALL VIEWS IN SCHEMA AGENT_API TO ROLE PVSWEEP_PIPELINE;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA AGENT_API TO ROLE PVSWEEP_PIPELINE;
GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA SWEEP, AUDIT TO ROLE PVSWEEP_PIPELINE;
GRANT SELECT, INSERT ON FUTURE TABLES IN SCHEMA SWEEP, AUDIT TO ROLE PVSWEEP_PIPELINE;
GRANT INSERT ON ALL TABLES IN SCHEMA EVAL TO ROLE PVSWEEP_PIPELINE;
GRANT INSERT ON FUTURE TABLES IN SCHEMA EVAL TO ROLE PVSWEEP_PIPELINE;
GRANT READ, WRITE ON STAGE OPS.LOAD_STAGE TO ROLE PVSWEEP_PIPELINE;

-- Agents: the secure views only.
GRANT USAGE ON SCHEMA AGENT_API TO ROLE PVSWEEP_AGENT;
GRANT SELECT ON ALL VIEWS IN SCHEMA AGENT_API TO ROLE PVSWEEP_AGENT;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA AGENT_API TO ROLE PVSWEEP_AGENT;

-- Review app: read what review needs, insert decisions.
GRANT USAGE ON SCHEMA REF, SRC, PV, SWEEP, REVIEW, AUDIT, REPORT TO ROLE PVSWEEP_REVIEW_APP;
GRANT SELECT ON ALL TABLES IN SCHEMA REF, SRC, PV, SWEEP, REVIEW, AUDIT TO ROLE PVSWEEP_REVIEW_APP;
GRANT SELECT ON FUTURE TABLES IN SCHEMA REF, SRC, PV, SWEEP, REVIEW, AUDIT TO ROLE PVSWEEP_REVIEW_APP;
GRANT SELECT ON ALL VIEWS IN SCHEMA REPORT TO ROLE PVSWEEP_REVIEW_APP;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA REPORT TO ROLE PVSWEEP_REVIEW_APP;
GRANT INSERT ON ALL TABLES IN SCHEMA REVIEW TO ROLE PVSWEEP_REVIEW_APP;
GRANT INSERT ON FUTURE TABLES IN SCHEMA REVIEW TO ROLE PVSWEEP_REVIEW_APP;

-- Analysts: report views only.
GRANT USAGE ON SCHEMA REPORT TO ROLE PVSWEEP_ANALYST;
GRANT SELECT ON ALL VIEWS IN SCHEMA REPORT TO ROLE PVSWEEP_ANALYST;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA REPORT TO ROLE PVSWEEP_ANALYST;

-- CI: like pipeline plus agent, plus the right to clone the database (granted in bootstrap).
GRANT ROLE PVSWEEP_PIPELINE, ROLE PVSWEEP_AGENT TO ROLE PVSWEEP_CI;
