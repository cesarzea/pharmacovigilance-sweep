-- Load the staged Parquet files (data/stage) into Snowflake. Run as PVSWEEP_ADMIN after
-- `make stage-data` has PUT the files (scripts/snow_load.sh does both).
-- Loads are full replacements of the reference, safety-database and benchmark tables.
USE ROLE PVSWEEP_ADMIN;
USE DATABASE PVSWEEP;
USE WAREHOUSE PVSWEEP_WH;

TRUNCATE TABLE PV.SAFETY_CASE;
TRUNCATE TABLE PV.CASE_DRUG;
TRUNCATE TABLE PV.CASE_EVENT;
TRUNCATE TABLE PV.CASE_INDICATION;
TRUNCATE TABLE EVAL.VAERS_CODING;
TRUNCATE TABLE EVAL.VAERS_OUTCOMES;
TRUNCATE TABLE REF.PT_VOCAB;
DELETE FROM REF.DATA_SOURCE;

COPY INTO PV.SAFETY_CASE      FROM @OPS.LOAD_STAGE/safety_case.parquet      FILE_FORMAT = (TYPE = PARQUET) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO PV.CASE_DRUG        FROM @OPS.LOAD_STAGE/case_drug.parquet        FILE_FORMAT = (TYPE = PARQUET) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO PV.CASE_EVENT       FROM @OPS.LOAD_STAGE/case_event.parquet       FILE_FORMAT = (TYPE = PARQUET) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO PV.CASE_INDICATION  FROM @OPS.LOAD_STAGE/case_indication.parquet  FILE_FORMAT = (TYPE = PARQUET) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO EVAL.VAERS_CODING   FROM @OPS.LOAD_STAGE/vaers_coding.parquet     FILE_FORMAT = (TYPE = PARQUET) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO EVAL.VAERS_OUTCOMES FROM @OPS.LOAD_STAGE/vaers_outcomes.parquet   FILE_FORMAT = (TYPE = PARQUET) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO REF.PT_VOCAB        FROM @OPS.LOAD_STAGE/pt_vocab.parquet         FILE_FORMAT = (TYPE = PARQUET) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO REF.DATA_SOURCE     FROM @OPS.LOAD_STAGE/data_source.parquet      FILE_FORMAT = (TYPE = PARQUET) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

SELECT target_table, row_count, licence, date_offset_days FROM REF.DATA_SOURCE ORDER BY 1;
